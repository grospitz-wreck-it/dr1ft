-- DR1FT: make learning progress system-managed and protect student records.
--
-- Live policies currently allow authenticated users to INSERT/UPDATE/DELETE
-- their own mission, arc, unlock and competency rows. That lets a learner
-- write completion state or competency evidence directly instead of earning
-- it through the validated interaction/mission pipeline.
--
-- The competency SELECT policy also exposes every learner's competency
-- progress to any member of the same class instance. Student-level learning
-- records must not be visible to classmates.
--
-- The verified write path is server-side SECURITY DEFINER logic:
-- user_interactions -> evaluate_missions_after_interaction ->
-- user_mission_progress -> competency/story-arc triggers.
-- Browser clients therefore receive SELECT only on these progress tables.

-- Competency progress: learners see only their own rows; assigned teachers
-- may inspect their class through the existing class-instance role helper.
drop policy if exists "members manage own scoped competency progress"
  on public.user_competency_progress;
drop policy if exists "members view instance competency progress"
  on public.user_competency_progress;

create policy "users read own scoped competency progress"
  on public.user_competency_progress
  for select
  to authenticated
  using (
    user_id = (select auth.uid())
    and class_instance_id is not null
    and public.is_member_of_class_instance(class_instance_id)
  );

create policy "assigned teachers read class competency progress"
  on public.user_competency_progress
  for select
  to authenticated
  using (public.is_teacher_of_class_instance(class_instance_id));

-- Mission progress: the mission evaluator creates completion records.
drop policy if exists "members manage own scoped mission progress"
  on public.user_mission_progress;

create policy "users read own scoped mission progress"
  on public.user_mission_progress
  for select
  to authenticated
  using (
    user_id = (select auth.uid())
    and class_instance_id is not null
    and exists (
      select 1
      from public.class_instance_memberships cim
      where cim.class_instance_id = user_mission_progress.class_instance_id
        and cim.user_id = (select auth.uid())
        and cim.left_at is null
    )
  );

create policy "assigned teachers read class mission progress"
  on public.user_mission_progress
  for select
  to authenticated
  using (public.is_teacher_of_class_instance(class_instance_id));

-- Story arc progress: only the arc-start and mission-completion workflows
-- may create or advance a learner's story state. Keep the existing own-row
-- SELECT policy; remove the broad ALL policy.
drop policy if exists "members manage own scoped arc progress"
  on public.user_story_arc_progress;

-- Unlocked missions: only trusted unlock/arc logic may create unlock records.
drop policy if exists "members manage own scoped unlocked missions"
  on public.user_unlocked_missions;

create policy "users read own scoped unlocked missions"
  on public.user_unlocked_missions
  for select
  to authenticated
  using (
    user_id = (select auth.uid())
    and class_instance_id is not null
    and public.is_member_of_class_instance(class_instance_id)
  );

-- Defense in depth: browser roles cannot mutate system-calculated learning
-- state even if another permissive policy is introduced later.
revoke insert, update, delete on table
  public.user_competency_progress,
  public.user_mission_progress,
  public.user_story_arc_progress,
  public.user_unlocked_missions
from anon, authenticated;

grant select on table
  public.user_competency_progress,
  public.user_mission_progress,
  public.user_story_arc_progress,
  public.user_unlocked_missions
to authenticated;

comment on table public.user_competency_progress is
  'System-managed learning evidence and competency state. Learners can read their own records; assigned teachers can read their class through RLS; browser writes are disabled.';

comment on table public.user_mission_progress is
  'System-managed mission completion state generated by validated interaction triggers; browser writes are disabled.';
